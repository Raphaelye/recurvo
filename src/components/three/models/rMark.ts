// The outline and hole as flat x, y lists, for the SVG fallback.
export const R_MARK = { outline: OUTLINE, hole: HOLE };

function points(flat: number[], scale: number) {
  const result: Vector2[] = [];
  for (let i = 0; i < flat.length; i += 2) {
    result.push(new Vector2(flat[i] * scale, flat[i + 1] * scale));
  }
  return result;
}

const cache = new Map<string, BufferGeometry>();

// The mark raised `depth` above z = 0, `size` wide, with rounded edges.
export function rMarkGeometry(size: number, depth: number) {
  const key = `${size}:${depth}`;
  let geometry = cache.get(key);
  if (!geometry) {
    const shape = new Shape(points(OUTLINE, size / 2));
    shape.holes.push(new Path(points(HOLE, size / 2)));
    const bevel = depth * 0.3;
    geometry = new ExtrudeGeometry(shape, {
      depth: depth - bevel * 2,
      bevelEnabled: true,
      bevelThickness: bevel,
      bevelSize: Math.min(bevel, size * 0.006),
      bevelSegments: 2,
      curveSegments: 1,
    });
    geometry.translate(0, 0, bevel);
    cache.set(key, geometry);
  }
  return geometry;
}

// Generates src/data/glyphs.ts: Plus Jakarta Sans ExtraBold outlines for the
// text inside the 3D scenes (the wordmark on the cards, the dates and months on
// the calendar). Uses the TTF loader that ships with three, so no extra package.
// Only the characters in CHARACTERS are kept, to keep the file small.
// Run: node scripts/generate-glyphs.js
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const FONT = "assets/fonts/PlusJakartaSans-ExtraBold.ttf";
const OUT = "src/data/glyphs.ts";

// Wordmark, digits, and the letters of the month abbreviations (JAN to DEC).
const CHARACTERS = "Recurvo0123456789ABCDEFGJLMNOPRSTUVY";

async function main() {
  const { TTFLoader } = await import("three/examples/jsm/loaders/TTFLoader.js");
  const file = fs.readFileSync(path.join(root, FONT));
  const buffer = file.buffer.slice(file.byteOffset, file.byteOffset + file.byteLength);
  const font = new TTFLoader().parse(buffer);

  const glyphs = {};
  for (const character of new Set(CHARACTERS)) {
    const glyph = font.glyphs[character];
    if (!glyph) {
      throw new Error(`Missing glyph "${character}" in ${FONT}`);
    }
    glyphs[character] = glyph;
  }

  const data = {
    glyphs,
    familyName: font.familyName,
    ascender: font.ascender,
    descender: font.descender,
    underlinePosition: font.underlinePosition,
    underlineThickness: font.underlineThickness,
    boundingBox: font.boundingBox,
    resolution: font.resolution,
    original_font_information: {},
  };

  const source = `// Generated by scripts/generate-glyphs.js from ${FONT}. Do not edit by hand.
// Typeface outlines for three's Font (three/examples/jsm/loaders/FontLoader.js).
// Characters: ${CHARACTERS}

export const glyphs = ${JSON.stringify(data)};
`;
  fs.writeFileSync(path.join(root, OUT), source);
  console.log(`Wrote ${OUT} (${Object.keys(glyphs).length} glyphs, ${source.length} bytes)`);
}

main();
